package com.pratik.crud.controller;
import java.util.Optional;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.HttpStatus;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.server.ResponseStatusException;

import com.pratik.crud.model.User;
import com.pratik.crud.userRepository.UserRepository;

@RestController
public class MainController  {
	
	@Autowired
	UserRepository userRepo;
	
	@GetMapping("/all")
	public Iterable<User> getAll() {
	    // This returns a JSON or XML with the users
	    return userRepo.findAll();
	  }
	
	@PostMapping(path= "/reg", consumes = "application/json", produces = "application/json")
	public  String addNewUser (@RequestBody User user) 
	{
		// Reject malformed input (400) before anything is persisted.
		validateUserInput(user);
		// Always create a fresh entity: only the client-editable fields are copied,
		// so the id is generated by the server and an existing row cannot be overwritten.
		User u = new User();
		u.setName(user.getName());
		u.setSal(user.getSal());
		userRepo.save(u);
		
		return "Data successfully saved in Database";
		
	}
	
	@PutMapping("/update/{id}")
	public  String updateData (@PathVariable int id, @RequestBody User user) 
	{
		// Reject malformed input (400) before the stored record is looked up or modified.
		validateUserInput(user);
		Optional<User> u=userRepo.findById(id);
		if(u.isPresent())
		{
			// Copy only the editable fields onto the persisted entity; the target
			// record is chosen by the path id, never by a body-bound entity id.
			User existing = u.get();
			existing.setName(user.getName());
			existing.setSal(user.getSal());
			userRepo.save(existing);
			return "Data updated successfully saved in Database";
		}
		else
		{
			
			return "Data not exist in Database";
		}
	
	}

	// Matches the default JPA/Hibernate VARCHAR length used for the unannotated String columns of User.
	private static final int MAX_FIELD_LENGTH = 255;

	private static void validateUserInput(User user) {
		if (user == null) {
			throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Request body is required");
		}
		requireText("name", user.getName());
		requireText("sal", user.getSal());
	}

	private static void requireText(String field, String value) {
		if (value == null || value.trim().isEmpty()) {
			throw new ResponseStatusException(HttpStatus.BAD_REQUEST, field + " must not be blank");
		}
		if (value.length() > MAX_FIELD_LENGTH) {
			throw new ResponseStatusException(HttpStatus.BAD_REQUEST, field + " must be at most " + MAX_FIELD_LENGTH + " characters");
		}
	}

	@DeleteMapping(path= "/delete", consumes = "application/json", produces = "application/json")
	public  String deleteData (@RequestParam int id ) 
	{
		//User u=(User)userRepo.findAllById(id);
//		u.setName(name);
//		u.setSal(sal);
		//System.out.println(u);
		
		//userRepo.save(u);
		userRepo.deleteById(id);
		
		return "Data Deleted ";
		
	}
	

	
	
	

}
