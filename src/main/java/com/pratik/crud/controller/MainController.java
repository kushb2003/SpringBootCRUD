package com.pratik.crud.controller;
import java.util.Optional;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.http.HttpStatus;
import org.springframework.web.server.ResponseStatusException;

import com.pratik.crud.dto.CreateUserRequest;
import com.pratik.crud.dto.UpdateUserRequest;
import com.pratik.crud.model.User;
import com.pratik.crud.userRepository.UserRepository;

@RestController
public class MainController  {
	
	@Autowired
	UserRepository userRepo;
	
	@PreAuthorize("hasRole('ADMIN')")
	@GetMapping("/all")
	public Iterable<User> getAll() {
	    // This returns a JSON or XML with the users
	    return userRepo.findAll();
	  }
	
	@PreAuthorize("hasRole('ADMIN')")
	@PostMapping(path= "/reg", consumes = "application/json", produces = "application/json")
	public  String addNewUser (@RequestBody CreateUserRequest request) 
	{
		if (request == null || isBlank(request.getName()) || isBlank(request.getSal()))
		{
			throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "name and sal are required");
		}
		// Always a fresh entity: the id is generated by the persistence layer, so save() inserts.
		User u = new User();
		u.setName(request.getName());
		u.setSal(request.getSal());
		userRepo.save(u);
		
		return "Data successfully saved in Database";
		
	}
	
	//@PutMapping(path= "/update", consumes = "application/json", produces = "application/json")
	@PreAuthorize("hasRole('ADMIN')")
	@PutMapping("/update")
	public  String updateData (@RequestBody UpdateUserRequest request) 
	{
		if (request == null || request.getId() == null || isBlank(request.getName()) || isBlank(request.getSal()))
		{
			throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "id, name and sal are required");
		}
		Optional<User> u=userRepo.findById(request.getId());
		if(u.isPresent())
		{
		// Copy only the permitted fields onto the managed entity; the id is never taken from the body.
		User existing = u.get();
		existing.setName(request.getName());
		existing.setSal(request.getSal());
		userRepo.save(existing);
		return "Data updated successfully saved in Database";
		}
		else
		{
			
			return "Data not exist in Database";
		}
	
	}

	private static boolean isBlank(String value)
	{
		return value == null || value.trim().isEmpty();
	}

	@PreAuthorize("hasRole('ADMIN')")
	@DeleteMapping(path= "/delete", consumes = "application/json", produces = "application/json")
	public  String deleteData (@RequestParam int id ) 
	{
		//User u=(User)userRepo.findAllById(id);
//		u.setName(name);
//		u.setSal(sal);
		//System.out.println(u);
		
		//userRepo.save(u);
		userRepo.deleteById(id);
		
		return "Data Deleted ";
		
	}
	

	
	
	

}
